def generate_catalog():
    source_file = Path('i18n/extracted_strings.json')
    if not source_file.exists():
        print("Error: primero ejecuta scripts/i18n_scanner.py")
        return

    data = json.loads(source_file.read_text(encoding='utf-8'))
    unique_texts = sorted(list({item['text_en'] for item in data['strings']}))

    catalog = {}
    missing = []

    for text in unique_texts:
        if text in FULL_TRANSLATIONS:
            catalog[text] = FULL_TRANSLATIONS[text]
        else:
            catalog[text] = f"[TODO: {text}]"
            missing.append(text)

    output_path = Path('i18n/translations_es.json')
    with open(output_path, 'w', encoding='utf-8') as f:
        json.dump(catalog, f, ensure_ascii=False, indent=2)

    print(f"Catálogo generado con éxito en: {output_path}")
    print(f"Total de cadenas en catálogo: {len(catalog)}")
    print(f"Traducciones completadas: {len(catalog) - len(missing)}")
    print(f"Cadenas pendientes: {len(missing)}")
    if missing:
        print("Pendientes:", missing)

if __name__ == '__main__':
    generate_catalog()
